package labelSet;

public class Hrana {
    private int odkial;
    private int kam;
    private int cena;

    public Hrana(int odkial, int kam, int cena) {
        this.odkial = odkial;
        this.kam = kam;
        this.cena = cena;
    }

    public int getOdkial() {
        return this.odkial;
    }

    public int getKam() {
        return this.kam;
    }

    public int getCena() {
        return this.cena;
    }
}
